test('wyniki wyrażeń', async (t) => {
  for (const [expr, ctx, want] of CASES) {
    await t.test(`${expr} [${ctx}]`, () => {
      if (!Array.isArray(want)) {
        assert.throws(() => evaluate(expr, CTX[ctx]), (e) => e instanceof CalcError && e.message === want.err);
        return;
      }
      const r = evaluate(expr, CTX[ctx]);
      assert.ok(close(r.v, want[0]), `wartość ${r.v}, oczekiwano ${want[0]}`);
      assert.equal(unitLabel(r.u), want[1]);
      assert.equal(r.notes.length, want[2] || 0, 'notki: ' + r.notes.join(' | '));
    });
  }
});

// Wynik wstawiony kliknięciem albo wklejony ze schowka musi dać ten sam wynik – także gdy istnieją
// zmienne o nazwach jednostek (m, s, h, t, T, K, A, V).
test('wstaw / kopiuj → policz daje to samo', () => {
  const clash = { m: { v: 2, u: { kg: 1 } }, s: { v: 1, u: { m: 1 } }, h: { v: 5, u: { m: 1 } }, t: { v: 3, u: { s: 1 } }, T: { v: 300, u: { K: 1 } }, K: { v: 1, u: {} }, A: { v: 2, u: { m: 2 } }, V: { v: 1, u: { m: 3 } } };
  const exprs = [...Object.keys(CONST), 'sqrt(5 m)', '2 m/s * 3 kg', '1/(2 s)', '5 N*m', '2 1/(m*s)', '3 m^3/(kg*s)', '4 A*s/kg', 'sqrt(2 m)*3 s', '6 mol/(m^3*K)', 'cbrt(8 m^3)'];
  for (const vars of [{}, clash]) for (const e of exprs) {
    const r = evaluate(e);
    for (const text of [insertText(r.v, r.u), copyText(r.v, r.u)]) {
      const b = evaluate(text, { vars });
      assert.ok(close(b.v, r.v) && unitLabel(b.u) === unitLabel(r.u), `${e} → „${text}” = ${b.v} ${unitLabel(b.u)}`);
    }
  }
});

